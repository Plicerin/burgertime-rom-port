// Writes src/btimeGfxData.mjs: the board's graphics ROMs (characters and
// sprites, background tiles, background map) as data for the renderer.
//   node tools/gen-gfx.mjs
import { writeFileSync } from 'node:fs';
import { loadRoms } from './oracle.mjs';

const { gfx1, gfx2, bgMap } = loadRoms();
const hexLines = (bytes) => Buffer.from(bytes).toString('hex').match(/.{1,128}/g).map((l) => `  '${l}'`).join(',\n');
writeFileSync(new URL('../src/btimeGfxData.mjs', import.meta.url), `// GENERATED by tools/gen-gfx.mjs from the graphics ROMs -- do not edit.
// GFX1: aa12.7k ab13.9k ab10.10k ab11.12k aa8.13k ab9.15k (characters and
// sprites, 3 bit planes); GFX2: ab00.1b ab01.3b ab02.4b (background tiles);
// BG_MAP: ab03.6b (background tile map).

const bytes = (lines) => Uint8Array.from(lines.join('').match(/../g), (h) => parseInt(h, 16));

export const GFX1 = bytes([
${hexLines(gfx1)},
]);

export const GFX2 = bytes([
${hexLines(gfx2)},
]);

export const BG_MAP = bytes([
${hexLines(bgMap)},
]);
`);
console.log(`gfx: ${gfx1.length + gfx2.length + bgMap.length} bytes`);
